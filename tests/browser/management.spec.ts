import { expect, test } from '@playwright/test'
import { fixtureSession, openDemo } from './demo.ts'

test('native account menu owns management, keeps keyboard/focus and leaves desktop unchanged', async ({ page, isMobile }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => { errors.push(error.message) })
  await openDemo(page)
  if (!isMobile) {
    await expect(page.locator('[data-mobile-management-anchor]')).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Plugins', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Collapse sidebar', exact: true })).toBeVisible()
    return
  }
  await page.getByRole('button', { name: 'Sessions', exact: true }).click()
  const account = page.getByRole('button', { name: 'Account menu', exact: true })
  await expect(page.locator('[data-mobile-management-anchor]')).toBeVisible()
  const box = await account.boundingBox()
  expect(box?.width).toBe(44)
  expect(box?.height).toBe(44)
  await expect(account.locator('[class*="_label"]')).toBeHidden()
  await account.focus()
  await page.keyboard.press('Enter')
  const menu = page.locator('[data-mobile-management-menu]')
  await expect(menu).toBeVisible()
  await expect(menu.getByRole('menuitem', { name: 'Plugins', exact: true })).toBeVisible()
  await expect(menu.getByRole('menuitem', { name: 'Settings', exact: true })).toBeVisible()
  await expect(menu.getByRole('menuitem', { name: 'Plugins', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(menu.getByRole('menuitem', { name: 'Automation tasks', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).toHaveCount(0)
  await expect(account).toBeFocused()
  await account.click()
  await page.getByRole('menuitem', { name: 'Plugins', exact: true }).click()
  const plugins = page.locator('[data-mobile-management-surface="plugins"]')
  await expect(plugins).toBeVisible()
  await expect(page.locator('[data-mobile-workbench="navigation"]')).toBeHidden()
  expect((await plugins.boundingBox())?.x).toBe(8)
  expect((await plugins.boundingBox())?.width).toBe(page.viewportSize()!.width - 16)
  await plugins.getByRole('button', { name: 'Choose how to add a plugin', exact: true }).click()
  await expect(page.locator('[role=menu]')).toBeVisible()
  await page.goBack()
  await expect(page.locator('[role=menu]')).toHaveCount(0)
  await expect(plugins).toBeVisible()
  await plugins.getByRole('button', { name: 'Back to sessions', exact: true }).click()
  await expect(plugins).toHaveCount(0)
  await expect(page.locator('html')).toHaveAttribute('data-mobile-workbench-page', 'sessions')
  await expect(account).toBeFocused()
  await account.click()
  await page.getByRole('menuitem', { name: 'Settings', exact: true }).click()
  const settings = page.locator('[data-mobile-management-surface="settings"]')
  await expect(settings).toBeVisible()
  expect((await settings.boundingBox())?.x).toBe(8)
  await page.goBack()
  await expect(settings).toHaveCount(0)
  await expect(page.locator('html')).toHaveAttribute('data-mobile-workbench-page', 'sessions')
  await account.click()
  await page.getByRole('menuitem', { name: 'Automation tasks', exact: true }).click()
  const tasks = page.locator('[data-mobile-management-surface="panel"]')
  await expect(tasks).toBeVisible()
  expect((await tasks.boundingBox())?.width).toBe(page.viewportSize()!.width - 16)
  await expect(page.locator('[data-workbench-destination="session"]')).not.toHaveAttribute('aria-current', 'page')
  await page.goBack()
  await expect(tasks).toHaveCount(0)
  await expect(page.locator('html')).toHaveAttribute('data-mobile-workbench-page', 'sessions')
  await account.click()
  await page.getByRole('menuitem', { name: 'Automation tasks', exact: true }).click()
  await expect(tasks).toBeVisible()
  await tasks.getByRole('button', { name: 'New', exact: true }).click()
  await expect(tasks).toHaveCount(0)
  await expect(page.locator('[data-mobile-workbench="navigation"]')).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-mobile-workbench-page', 'session')
  await page.screenshot({ path: info.outputPath('management-return.png') })
  expect(errors).toEqual([])
})

test('management preserves list scroll, footer reachability and media disposal', async ({ page, isMobile }) => {
  test.skip(!isMobile)
  await openDemo(page)
  await page.getByRole('button', { name: 'Sessions', exact: true }).click()
  await page.evaluate(() => {
    const list = document.querySelector<HTMLElement>('[data-slot="sidebar.workspaces"] [class$="_list"]')!
    list.id = 'management-scroll-fixture'
    const filler = document.createElement('div')
    filler.style.cssText = 'height:2600px;flex:none'
    filler.setAttribute('aria-hidden', 'true')
    list.append(filler)
    list.scrollTop = 500
    const footer = document.querySelector('[data-mobile-nav="frame"] [class*="_footArea"]')!
    const extension = document.createElement('button')
    extension.textContent = 'Extension action'
    extension.style.cssText = 'height:44px'
    extension.onclick = () => { extension.dataset.activated = 'true' }
    footer.append(extension)
  })
  const scroll = page.locator('#management-scroll-fixture')
  await expect.poll(() => scroll.evaluate(e => e.scrollTop)).toBe(500)
  await page.getByRole('button', { name: 'Extension action' }).click()
  await expect(page.getByRole('button', { name: 'Extension action' })).toHaveAttribute('data-activated', 'true')
  const account = page.getByRole('button', { name: 'Account menu', exact: true })
  await account.click()
  expect((await account.boundingBox())?.y).toBe(14)
  await page.getByRole('menuitem', { name: 'Automation tasks', exact: true }).click()
  await page.locator('[data-mobile-management-chrome]').getByRole('button', { name: 'Back to sessions', exact: true }).click()
  await expect(page.locator('[data-mobile-management-surface]')).toHaveCount(0)
  await expect.poll(() => scroll.evaluate(e => e.scrollTop)).toBe(500)
  await expect(account).toBeFocused()
  await page.setViewportSize({ width: 1440, height: 900 })
  await expect(page.locator('[data-mobile-management-anchor]')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Plugins', exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Sessions', exact: true }).click()
  await expect(page.locator('[data-mobile-management-anchor]')).toBeVisible()
  await account.click()
  await expect(page.locator('[data-mobile-management-entry]')).toHaveCount(2)
  await page.keyboard.press('Escape')
})

test('immutable preset is only a read-only sibling in the current Session menu', async ({ page, isMobile }) => {
  await fixtureSession(page)
  await expect(page.locator('[data-workbench-header-secondary] [data-workbench-mode]')).toHaveCount(0)
  await page.locator('header button[class*="_moreButton"]').click()
  const info = page.locator('[data-mobile-workbench-session-preset]')
  if (!isMobile) { await expect(info).toHaveCount(0); return }
  await expect(info).toBeVisible()
  await expect(info).toHaveAttribute('role', 'note')
  await expect(info).not.toHaveAttribute('tabindex')
  await expect(info).toContainText('Preset (fixed for this session)')
  await expect(info.locator('button,[role="menuitem"]')).toHaveCount(0)
  expect(await info.evaluate(e => e.closest('[data-mobile-workbench-session-copy]') === null)).toBe(true)
  expect(await info.getAttribute('title')).toBe(await info.textContent())
  await info.click()
  await expect(info).toBeVisible()
  await expect(page.locator('[data-mobile-workbench-session-copy] button')).not.toHaveAttribute('aria-label')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Sessions', exact: true }).click()
  await page.getByRole('button', { name: 'Account menu', exact: true }).click()
  await expect(info).toHaveCount(0)
})

test('first Automation New after closing a management Modal is an outward action, not Back', async ({ page, isMobile }) => {
  test.skip(!isMobile)
  await openDemo(page)
  await page.getByRole('button', { name: 'Sessions', exact: true }).click()
  await page.getByRole('button', { name: 'Account menu', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Plugins', exact: true }).click()
  await page.locator('[data-mobile-management-surface=plugins]').getByRole('button', { name: 'Back to sessions', exact: true }).click()
  await expect(page.locator('[data-mobile-management-surface]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Account menu', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Automation tasks', exact: true }).click()
  await page.locator('[data-mobile-management-surface=panel]').getByRole('button', { name: 'New', exact: true }).click()
  await expect(page.locator('[data-mobile-management-surface]')).toHaveCount(0)
  await expect(page.locator('html')).toHaveAttribute('data-mobile-workbench-page', 'session')
  await expect.poll(() => page.evaluate(() => history.state?.mobilePanelExit)).not.toBe(true)
})
