import { expect, test } from '@playwright/test'
import { fixtureSession } from './demo.ts'

test('descendant keyboard focus, escape, direct parents and nested 44px header geometry', async ({ page, isMobile }, info) => {
  test.skip(!isMobile)
  const errors: string[] = []
  page.on('pageerror', error => { errors.push(error.message) })
  await fixtureSession(page, { reuse: false })
  const agents = page.locator('[data-mobile-workbench="agents"]')
  if (await agents.isDisabled()) {
    await page.locator('[data-composer-input]').fill('演示多层子智能体')
    await page.getByRole('button', { name: 'Send message', exact: true }).click()
    await expect(page.getByText(/MOBILE_AUDIT_NESTED_ROOT_(?:NOT_)?COMPLETE/).last()).toBeVisible({ timeout: 60_000 })
  }
  await expect(agents).toBeEnabled({ timeout: 60_000 })
  const tree = page.locator('[role="tree"][class*="_menuBody"]')
  const editor = page.locator('[data-composer-input]')
  await editor.focus()
  await agents.click()
  await expect(tree).toBeVisible()
  await expect(editor).toBeFocused()
  await agents.click()
  await expect(tree).toHaveCount(0)
  const stats = page.locator('[data-mobile-workbench="stats"]')
  await stats.click()
  await agents.focus()
  await agents.press('Enter')
  await expect(page.locator('[data-workbench-stats-panel]')).toHaveCount(0)
  await expect(tree).toBeVisible()
  await stats.click()
  await expect(tree).toHaveCount(0)
  await expect(page.locator('[data-workbench-stats-panel]')).toBeVisible()
  await stats.click()
  for (const key of ['Enter', ' ', 'ArrowDown']) {
    await agents.focus()
    await agents.press(key)
    await expect(tree).toBeVisible()
    await expect.poll(() => page.evaluate(() => !!document.activeElement?.matches('[role="treeitem"]'))).toBe(true)
    await page.keyboard.press('Escape')
    await expect(tree).toHaveCount(0)
    await expect(agents).toBeFocused()
  }
  await agents.press('Enter')
  const parentName = 'MOBILE_AUDIT_NESTED_B · 两层目录父节点'
  await expect(tree.getByText(parentName, { exact: true })).toBeVisible()
  const targets = tree.locator('button[class*="_disclosure"], button[class*="_sidebarButton"]')
  for (let i = 0; i < await targets.count(); i++) {
    const el = targets.nth(i)
    const hit = await el.evaluate(node => {
      const r = node.getBoundingClientRect()
      return { width: r.width, height: r.height, edges: [[r.x+1,r.y+r.height/2],[r.right-1,r.y+r.height/2]].map(([x,y]) => node.contains(document.elementFromPoint(x!,y!))) }
    })
    expect(hit.width).toBeGreaterThanOrEqual(44)
    expect(hit.height).toBeGreaterThanOrEqual(44)
    expect(hit.edges).toEqual([true,true])
  }
  await tree.getByText(parentName, { exact: true }).click()
  const title = page.locator('[data-workbench-title-info]')
  await expect(title).toContainText('MOBILE_AUDIT_NESTED_PARENT_TASK')
  await expect(page.locator('[data-mobile-workbench="parent"]')).toHaveAccessibleName(/开始手机界面审计/)
  await expect.poll(async () => (await page.locator('[data-mobile-workbench-header]').boundingBox())!.height).toBeLessThanOrEqual(112)
  const parentTitle = await title.innerText()
  await page.screenshot({ path: '.demo-home/review/a/after-child-' + info.project.name + '.png' })
  await agents.click()
  await expect(tree).toBeVisible()
  const leaf = tree.getByText('MOBILE_AUDIT_NESTED_D · 只读叶子', { exact: true })
  await expect(leaf).toBeVisible({ timeout: 60_000 })
  await leaf.click()
  await expect(title).toContainText('MOBILE_AUDIT_NESTED_LEAF_TASK')
  await expect(page.locator('[data-mobile-workbench="parent"]')).toHaveAccessibleName(new RegExp(parentTitle))
  await expect.poll(async () => (await page.locator('[data-mobile-workbench-header]').boundingBox())!.height).toBeLessThanOrEqual(112)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '.demo-home/review/a/after-grandchild-' + info.project.name + '.png' })
  await page.locator('[data-mobile-workbench="parent"]').click()
  await expect(title).toContainText('MOBILE_AUDIT_NESTED_PARENT_TASK')
  await page.locator('[data-mobile-workbench="parent"]').click()
  await expect(title).toContainText('开始手机界面审计')
  expect(errors).toEqual([])
})

test('session More is a real 44px target, menu retains actions and row center navigates', async ({ page, isMobile }, info) => {
  test.skip(!isMobile)
  await fixtureSession(page, { reuse: false })
  await page.locator('[data-workbench-destination="sessions"]').click()
  const row = page.locator('[data-row-key^="session:"]').filter({ hasText: '开始手机界面审计' }).first()
  await expect(row).toBeVisible()
  expect((await row.boundingBox())!.height).toBeGreaterThanOrEqual(44)
  const actions = row.locator('[class*="_rowActions"] button:visible')
  await expect(actions).toHaveCount(1)
  for (let i = 0; i < await actions.count(); i++) {
    const action = actions.nth(i)
    await action.scrollIntoViewIfNeeded()
    const hit = await action.evaluate(node => {
      const r = node.getBoundingClientRect()
      return { width: r.width, height: r.height, hit: node.contains(document.elementFromPoint(r.right-1,r.y+r.height/2)) }
    })
    expect(hit.width).toBeGreaterThanOrEqual(44)
    expect(hit.height).toBeGreaterThanOrEqual(44)
    expect(hit.hit).toBe(true)
  }
  await actions.first().click()
  const menu = page.getByRole('menu')
  await expect(menu.getByRole('menuitem', { name: 'Archive session', exact: true })).toBeVisible()
  await expect(menu.getByRole('menuitem', { name: 'Pin session', exact: true })).toBeVisible()
  await page.screenshot({ path: '.demo-home/review/a/after-session-actions-' + info.project.name + '.png' })
  await page.keyboard.press('Escape')
  const safeCenter = await row.evaluate(node => {
    const r = node.getBoundingClientRect()
    return !document.elementFromPoint(r.x + r.width/2, r.y + r.height/2)?.closest('button')
  })
  expect(safeCenter).toBe(true)
  await row.click()
  await expect(page.locator('[data-workbench-title-info]')).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-mobile-workbench-page', 'session')
})
